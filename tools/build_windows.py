"""Build the Windows distribution of MCServer: the standalone app folder and its installer (M5).

Run from the repository root with the project's virtual environment::

    .venv\\Scripts\\python tools\\build_windows.py

Steps:

1. Read the version and the app's identity from ``src/mcserver/__init__.py`` (the one place to change them).
2. Draw the icon (``.ico``) and the installer images from the logo embedded in the app.
3. Write the Windows version resource (Explorer → Properties → Details).
4. Run PyInstaller with ``packaging/windows/MCServer.spec`` → ``dist/windows/MCServer/MCServer.exe``.
5. Run Inno Setup with ``packaging/windows/MCServer.iss`` → ``dist/windows/MCServer-<version>-setup.exe``.

Generated files go to ``build/windows`` and ``dist/windows``; both are ignored by Git.
Nothing is downloaded: PyInstaller comes from the dev dependencies, Inno Setup 6 must be installed.
"""

from __future__ import annotations

import argparse
import ast
import os
import re
import shutil
import struct
import subprocess  # nosec B404 (runs the build tools with fixed arguments)
import sys
from dataclasses import dataclass
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PACKAGE_INIT = ROOT / "src" / "mcserver" / "__init__.py"
SPEC = ROOT / "packaging" / "windows" / "MCServer.spec"
INSTALLER_SCRIPT = ROOT / "packaging" / "windows" / "MCServer.iss"
BUILD_DIR = ROOT / "build" / "windows"
DIST_DIR = ROOT / "dist" / "windows"
EXE_NAME = "MCServer.exe"
ICO_SIZES = (16, 20, 24, 32, 40, 48, 64, 128, 256)
ISCC_CANDIDATES = (
    Path(os.environ.get("ProgramFiles(x86)", r"C:\Program Files (x86)")) / "Inno Setup 6" / "ISCC.exe",
    Path(os.environ.get("ProgramFiles", r"C:\Program Files")) / "Inno Setup 6" / "ISCC.exe",
    Path(os.environ.get("LOCALAPPDATA", "")) / "Programs" / "Inno Setup 6" / "ISCC.exe",
)


@dataclass(frozen=True, slots=True)
class Identity:
    """What Windows shows about MCServer, read from the package."""

    name: str
    version: str
    publisher: str
    copyright: str
    homepage: str
    description: str

    @property
    def file_version(self) -> tuple[int, int, int, int]:
        """Return the numeric version Windows resources need (``2.0.0a1`` → ``(2, 0, 0, 0)``)."""
        return file_version(self.version)


def read_identity(init_file: Path = PACKAGE_INIT) -> Identity:
    """Return the constants assigned in ``init_file`` without importing the package (no Qt needed)."""
    values: dict[str, str] = {}
    for node in ast.parse(init_file.read_text(encoding="utf-8")).body:
        if isinstance(node, ast.Assign) and isinstance(node.value, ast.Constant) and isinstance(node.value.value, str):
            for target in node.targets:
                if isinstance(target, ast.Name):
                    values[target.id] = node.value.value
    return Identity(
        name=values["APP_NAME"],
        version=values["__version__"],
        publisher=values["PUBLISHER"],
        copyright=values["COPYRIGHT"],
        homepage=values["HOMEPAGE"],
        description=values["DESCRIPTION"],
    )


def file_version(version: str) -> tuple[int, int, int, int]:
    """Return the leading release numbers of ``version``, padded to four (pre-release tags are dropped)."""
    match = re.match(r"\d+(?:\.\d+)*", version)
    if match is None:
        raise ValueError(f"Not a version: {version!r}")
    numbers = [int(part) for part in match.group(0).split(".")][:4]
    return (*numbers, *([0] * (4 - len(numbers))))  # type: ignore[return-value]


def ico_bytes(images: dict[int, bytes]) -> bytes:
    """Return an ``.ico`` file holding one PNG per size (PNG entries are supported since Windows Vista)."""
    header = struct.pack("<HHH", 0, 1, len(images))
    directory = b""
    data = b""
    offset = 6 + 16 * len(images)
    for size, png in sorted(images.items()):
        side = 0 if size >= 256 else size  # 0 means 256 in the directory entry
        directory += struct.pack("<BBBBHHII", side, side, 0, 0, 1, 32, len(png), offset + len(data))
        data += png
    return header + directory + data


def version_resource(identity: Identity) -> str:
    """Return a PyInstaller version file (the details Explorer shows for ``MCServer.exe``)."""
    numbers = identity.file_version
    dotted = ".".join(str(number) for number in numbers)
    strings = {
        "CompanyName": identity.publisher,
        "FileDescription": identity.name,
        "FileVersion": identity.version,
        "InternalName": identity.name,
        "LegalCopyright": identity.copyright,
        "OriginalFilename": EXE_NAME,
        "ProductName": identity.name,
        "ProductVersion": identity.version,
        "Comments": identity.description,
    }
    entries = ",\n".join(f"          StringStruct({key!r}, {value!r})" for key, value in strings.items())
    return f"""# Generated by tools/build_windows.py ({dotted}); do not edit.
VSVersionInfo(
  ffi=FixedFileInfo(filevers={numbers}, prodvers={numbers}, mask=0x3F, flags=0x0, OS=0x40004,
                    fileType=0x1, subtype=0x0, date=(0, 0)),
  kids=[
    StringFileInfo([
      StringTable('040904B0', [
{entries}
      ])
    ]),
    VarFileInfo([VarStruct('Translation', [0x0409, 1200])])
  ]
)
"""


def draw_images(out: Path) -> dict[str, str]:
    """Draw the icon and installer images from the embedded logo; return their paths by role."""
    os.environ.setdefault("QT_QPA_PLATFORM", "offscreen")
    from PySide6.QtCore import QBuffer, QByteArray, QIODevice, QRectF, Qt
    from PySide6.QtGui import QColor, QGuiApplication, QImage, QLinearGradient, QPainter
    from PySide6.QtSvg import QSvgRenderer

    from mcserver.presentation.icons import LOGO_SVG

    _app = QGuiApplication.instance() or QGuiApplication([])
    renderer = QSvgRenderer(QByteArray(LOGO_SVG))

    def canvas(width: int, height: int) -> tuple[QImage, QPainter]:
        image = QImage(width, height, QImage.Format.Format_ARGB32_Premultiplied)
        image.fill(Qt.GlobalColor.transparent)
        painter = QPainter(image)
        painter.setRenderHint(QPainter.RenderHint.Antialiasing)
        return image, painter

    def logo(size: int) -> QImage:
        image, painter = canvas(size, size)
        renderer.render(painter, QRectF(0, 0, size, size))
        painter.end()
        return image

    def png(image: QImage) -> bytes:
        buffer = QBuffer()
        buffer.open(QIODevice.OpenModeFlag.WriteOnly)
        image.save(buffer, "PNG")  # type: ignore[call-overload]  # the stub says bytes, PySide6 wants str
        return bytes(buffer.data().data())

    out.mkdir(parents=True, exist_ok=True)
    icon = out / "MCServer.ico"
    icon.write_bytes(ico_bytes({size: png(logo(size)) for size in ICO_SIZES}))
    small = []
    for size in (55, 83, 110):  # 100 %, 150 %, 200 % — Inno Setup picks the closest
        path = out / f"wizard-small-{size}.png"
        path.write_bytes(png(logo(size)))
        small.append(path)
    large = []
    for scale in (1, 2):  # the Welcome/Finished pages' side image
        width, height = 164 * scale, 314 * scale
        image, painter = canvas(width, height)
        gradient = QLinearGradient(0, 0, width, height)
        gradient.setColorAt(0, QColor("#10251D"))
        gradient.setColorAt(1, QColor("#0B1A14"))
        painter.fillRect(0, 0, width, height, gradient)
        side = 88 * scale
        renderer.render(painter, QRectF((width - side) / 2, (height - side) / 2, side, side))
        painter.end()
        path = out / f"wizard-large-{scale}x.png"
        path.write_bytes(png(image))
        large.append(path)
    # Inno Setup takes a comma-separated list and picks the image closest to the screen's scaling.
    return {
        "icon": str(icon),
        "wizard_small": ",".join(str(path) for path in small),
        "wizard_large": ",".join(str(path) for path in large),
    }


def find_iscc(explicit: str | None) -> Path | None:
    """Return Inno Setup's compiler: ``explicit``, then ``ISCC`` on PATH, then the usual install folders."""
    if explicit:
        return Path(explicit)
    on_path = shutil.which("ISCC")
    if on_path:
        return Path(on_path)
    return next((path for path in ISCC_CANDIDATES if path.is_file()), None)


def run(command: list[str], **kwargs: object) -> None:
    """Run a build tool, echoing it; stop the build if it fails."""
    print("\n>", " ".join(f'"{part}"' if " " in part else part for part in command), flush=True)
    subprocess.run(command, check=True, cwd=ROOT, **kwargs)  # type: ignore[call-overload]  # nosec B603


def build_app(identity: Identity, images: dict[str, str]) -> Path:
    """Run PyInstaller; return the app folder (``dist/windows/MCServer``)."""
    version_file = BUILD_DIR / "version_info.txt"
    version_file.write_text(version_resource(identity), encoding="utf-8")
    environment = {**os.environ, "MCSERVER_ICON": images["icon"], "MCSERVER_VERSION_FILE": str(version_file)}
    run(
        [
            sys.executable,
            "-m",
            "PyInstaller",
            str(SPEC),
            "--noconfirm",
            "--clean",
            "--log-level",
            "WARN",
            "--distpath",
            str(DIST_DIR),
            "--workpath",
            str(BUILD_DIR / "pyinstaller"),
        ],
        env=environment,
    )
    app_dir = DIST_DIR / identity.name
    if not (app_dir / EXE_NAME).is_file():
        raise SystemExit(f"PyInstaller finished but {app_dir / EXE_NAME} is missing.")
    return app_dir


def build_installer(identity: Identity, images: dict[str, str], app_dir: Path, iscc: Path) -> Path:
    """Run Inno Setup; return the installer."""
    defines = {
        "AppName": identity.name,
        "AppVersion": identity.version,
        "AppFileVersion": ".".join(str(number) for number in identity.file_version),
        "AppPublisher": identity.publisher,
        "AppCopyright": identity.copyright,
        "AppHomepage": identity.homepage,
        "AppExeName": EXE_NAME,
        "SourceDir": str(app_dir),
        "OutputDir": str(DIST_DIR),
        "IconFile": images["icon"],
        "WizardSmall": images["wizard_small"],
        "WizardLarge": images["wizard_large"],
    }
    run([str(iscc), "/Qp", *(f"/D{key}={value}" for key, value in defines.items()), str(INSTALLER_SCRIPT)])
    installer = DIST_DIR / f"{identity.name}-{identity.version}-setup.exe"
    if not installer.is_file():
        raise SystemExit(f"Inno Setup finished but {installer} is missing.")
    return installer


def folder_size_mb(folder: Path) -> float:
    """Return the total size of the files in ``folder``."""
    return sum(path.stat().st_size for path in folder.rglob("*") if path.is_file()) / 1024 / 1024


def main(argv: list[str] | None = None) -> int:
    """Build the app and (unless skipped) the installer."""
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--skip-installer", action="store_true", help="build only dist/windows/MCServer")
    parser.add_argument("--iscc", help="path to Inno Setup's ISCC.exe (found automatically otherwise)")
    args = parser.parse_args(argv)
    if sys.platform != "win32":
        raise SystemExit("The Windows build runs on Windows only.")
    identity = read_identity()
    print(f"Building {identity.name} {identity.version}")
    iscc = None if args.skip_installer else find_iscc(args.iscc)
    if not args.skip_installer and (iscc is None or not iscc.is_file()):
        raise SystemExit(
            "Inno Setup 6 was not found. Install it (https://jrsoftware.org/isdl.php), "
            "pass --iscc PATH, or use --skip-installer."
        )
    sys.path.insert(0, str(ROOT / "src"))
    images = draw_images(BUILD_DIR)
    app_dir = build_app(identity, images)
    print(f"\nApp:       {app_dir} ({folder_size_mb(app_dir):.0f} MB)")
    if iscc is not None:
        installer = build_installer(identity, images, app_dir, iscc)
        print(f"\nInstaller: {installer} ({installer.stat().st_size / 1024 / 1024:.0f} MB)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
